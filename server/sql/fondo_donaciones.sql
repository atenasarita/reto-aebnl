-- ================================================================

-- Saldo global único
CREATE TABLE FONDO_DONACIONES (
    ID_FONDO            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALDO               NUMBER(12, 2) DEFAULT 0 NOT NULL,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CHK_FONDO_SALDO_NO_NEG CHECK (SALDO >= 0)
);

-- Fila inicial (único registro activo del fondo)
INSERT INTO FONDO_DONACIONES (SALDO) VALUES (0);

-- Movimientos de abono / egreso
CREATE TABLE MOVIMIENTOS_FONDO_DONACIONES (
    ID_MOVIMIENTO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_MOVIMIENTO     VARCHAR2(10) NOT NULL,
    MONTO               NUMBER(12, 2) NOT NULL,
    SALDO_ANTERIOR      NUMBER(12, 2) NOT NULL,
    SALDO_NUEVO         NUMBER(12, 2) NOT NULL,
    ORIGEN_TIPO         VARCHAR2(20),
    ORIGEN_NOMBRE       VARCHAR2(100),
    CONCEPTO            VARCHAR2(500),
    REQUIERE_REVISION   NUMBER(1) DEFAULT 0 NOT NULL,
    ID_SERVICIO_OTORGADO NUMBER,
    ID_USUARIO          NUMBER,
    FECHA               DATE DEFAULT SYSDATE NOT NULL,
    MOTIVO              VARCHAR2(200),
    CONSTRAINT CHK_MOV_FONDO_TIPO CHECK (TIPO_MOVIMIENTO IN ('abono', 'egreso')),
    CONSTRAINT CHK_MOV_FONDO_MONTO CHECK (MONTO > 0),
    CONSTRAINT CHK_MOV_FONDO_ORIGEN CHECK (
        ORIGEN_TIPO IS NULL OR ORIGEN_TIPO IN ('marca', 'familia')
    ),
    CONSTRAINT CHK_MOV_FONDO_REVISION CHECK (REQUIERE_REVISION IN (0, 1))
);

-- Columna en servicios financieros para desglose en recibos
ALTER TABLE SERVICIOS_FINANCIEROS ADD (
    MONTO_DONACION NUMBER(12, 2) DEFAULT 0
);

CREATE INDEX IDX_MOV_FONDO_FECHA ON MOVIMIENTOS_FONDO_DONACIONES (FECHA);
CREATE INDEX IDX_MOV_FONDO_SERVICIO ON MOVIMIENTOS_FONDO_DONACIONES (ID_SERVICIO_OTORGADO);
